import { build } from 'esbuild';
import fs from 'node:fs/promises';
import path from 'node:path';

const runtime = '.agents/skills/spec-driven-development/scripts/codex-spec.mjs';
const checking = process.argv.includes('--check');
const result = await build({
  entryPoints: ['src/cli.ts'], bundle: true, platform: 'node', format: 'esm', target: 'node22',
  outfile: runtime, write: false, legalComments: 'inline', charset: 'utf8',
  banner: { js: '#!/usr/bin/env node\n// Generated by npm run build. Edit src/*.ts, not this file.' }
});
const generated = result.outputFiles[0].contents;
if (checking) {
  const actual = await fs.readFile(runtime);
  if (!actual.equals(generated)) throw new Error('Bundled skill is stale. Run npm run build and commit the generated artifact.');
} else {
  await fs.mkdir(path.dirname(runtime), { recursive: true });
  await fs.writeFile(runtime, generated, { mode: 0o755 });
  await fs.chmod(runtime, 0o755);
  await build({ entryPoints: ['src/index.ts'], bundle: true, platform: 'node', format: 'esm',
    target: 'node22', outfile: '.build/index.mjs', legalComments: 'inline' });
}
console.log(checking ? 'Bundled skill matches TypeScript sources.' : 'Built the self-contained skill and test library.');
